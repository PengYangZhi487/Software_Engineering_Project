def build_docx(out_path: Path):
    doc = Document()
    doc.add_heading("校园选课系统需求说明书 V1.0", level=1)
    doc.add_paragraph("本文档用于 RATGP 平台实验，故意包含清晰、模糊、矛盾三类需求。")

    for rid, title, desc in REQUIREMENTS:
        doc.add_heading(f"{rid} {title}", level=2)
        doc.add_paragraph(desc)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(out_path))
    print(f"已生成: {out_path}  共 {len(REQUIREMENTS)} 条需求")


